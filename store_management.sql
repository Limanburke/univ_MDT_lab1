    price       numeric(12, 2) NOT NULL,
    is_deleted  boolean NOT NULL DEFAULT false,
    updated_at  timestamp without time zone NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_by  integer REFERENCES user_account(id),
    CONSTRAINT ck_product_price_nonnegative CHECK (price >= 0)
);

CREATE TABLE IF NOT EXISTS department_stock (
    department_id integer NOT NULL REFERENCES department(id),
    product_id    integer NOT NULL REFERENCES product(id),
    quantity      integer NOT NULL DEFAULT 0,
