CREATE TABLE IF NOT EXISTS position (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       varchar(100) NOT NULL,
    base_salary numeric(12, 2) NOT NULL,
    CONSTRAINT ck_position_base_salary_nonnegative CHECK (base_salary >= 0)
);

CREATE TABLE IF NOT EXISTS department (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(100) NOT NULL,
    manager_id integer, -- FK
    is_deleted boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS employee (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    varchar(50) NOT NULL,
    last_name     varchar(50) NOT NULL,
    department_id integer NOT NULL REFERENCES department(id),
    position_id   integer NOT NULL REFERENCES position(id),
    hire_date     date NOT NULL,
    is_deleted    boolean NOT NULL DEFAULT false,
    updated_at    timestamp without time zone NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_by    integer -- FK
);

CREATE TABLE IF NOT EXISTS user_account (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id   integer NOT NULL UNIQUE REFERENCES employee(id),
    username      varchar(50) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    is_active     boolean NOT NULL DEFAULT true,
    updated_at    timestamp without time zone NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_by    integer REFERENCES user_account(id)
);

