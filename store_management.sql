CREATE OR REPLACE VIEW v_user_audit_log AS
WITH audit_data AS (
    SELECT 
        e.updated_by AS user_id, 
        'Employee' AS entity_type, 
        e.id::varchar AS entity_id, 
        e.first_name || ' ' || e.last_name AS entity_details,
        e.updated_at 
    FROM employee e 
    WHERE e.updated_by IS NOT NULL

    UNION ALL

    SELECT 
        ua.updated_by, 
        'User Account', 
        ua.id::varchar, 
        'Username: ' || ua.username,
        ua.updated_at 
    FROM user_account ua 
    WHERE ua.updated_by IS NOT NULL

    UNION ALL

    SELECT 
        p.updated_by, 
        'Product', 
        p.id::varchar, 
        p.name || ' (' || p.sku || ')',
        p.updated_at 
    FROM product p 
    WHERE p.updated_by IS NOT NULL

    UNION ALL

    SELECT 
        ds.updated_by, 
        'Department Stock', 
        ds.department_id::varchar || '-' || ds.product_id::varchar, 
        d.name || ' / ' || p.name || ' (Qty: ' || ds.quantity || ')',
        ds.updated_at 
    FROM department_stock ds
    JOIN department d ON d.id = ds.department_id
    JOIN product p ON p.id = ds.product_id
    WHERE ds.updated_by IS NOT NULL

    UNION ALL

    SELECT 
        po.updated_by, 
        'Purchase Order', 
        po.id::varchar, 
        'Order #' || po.id || ' (' || s.name || ', Status: ' || po.status || ')',
        po.updated_at 
    FROM purchase_order po
    JOIN supplier s ON s.id = po.supplier_id
    WHERE po.updated_by IS NOT NULL

    UNION ALL

    SELECT 
        st.updated_by, 
        'Sales Transaction', 
        st.id::varchar, 
        'Receipt #' || st.id || ' (' || st.status || ', Total: ' || st.total_amount || ')',
        st.updated_at 
    FROM sales_transaction st 
    WHERE st.updated_by IS NOT NULL

    UNION ALL

    SELECT 
        pr.updated_by, 
        'Promotion', 
        pr.id::varchar, 
        pr.name || ' (' || pr.discount_percentage || '%)',
        pr.updated_at 
    FROM promotion pr 
    WHERE pr.updated_by IS NOT NULL
)
SELECT 
    ua.username,
    ad.entity_type,
    ad.entity_id,
    ad.entity_details,
    ad.updated_at
FROM audit_data ad
JOIN user_account ua ON ad.user_id = ua.id
ORDER BY ad.updated_at DESC NULLS LAST;

