CREATE TABLE IF NOT EXISTS purchase_order_item (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id integer NOT NULL REFERENCES purchase_order(id),
    product_id        integer NOT NULL REFERENCES product(id),
    quantity          integer NOT NULL,
    expected_price    numeric(12, 2) NOT NULL,
    CONSTRAINT ck_purchase_order_item_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_purchase_order_item_price_nonnegative CHECK (expected_price >= 0)
