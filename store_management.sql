CREATE OR REPLACE PROCEDURE sp_fire_employee(
    p_employee_id INT,
    p_admin_user_id INT
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_admin_employee_id INT;
BEGIN
    IF p_employee_id IS NULL THEN RAISE EXCEPTION 'Employee ID cannot be NULL';
    END IF;

    IF p_admin_user_id IS NULL THEN RAISE EXCEPTION 'Admin User ID cannot be NULL';
    END IF;

    SELECT employee_id INTO v_admin_employee_id 
    FROM user_account 
    WHERE id = p_admin_user_id AND is_active = true;

    IF v_admin_employee_id IS NULL THEN RAISE EXCEPTION 'Active administrator with User ID % not found', p_admin_user_id;
    END IF;

    IF p_employee_id = v_admin_employee_id THEN RAISE EXCEPTION 'Security violation: Administrator cannot dismiss their own account';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM employee WHERE id = p_employee_id AND is_deleted = false) THEN
        RAISE EXCEPTION 'Active employee with ID % does not exist', p_employee_id;
    END IF;

    IF EXISTS (SELECT 1 FROM department WHERE manager_id = p_employee_id AND is_deleted = false) THEN
        RAISE EXCEPTION 'Cannot fire employee %: they are currently assigned as a manager of an active department', p_employee_id;
    END IF;

    UPDATE employee 
    SET is_deleted = true, updated_by = p_admin_user_id
    WHERE id = p_employee_id;

    UPDATE user_account 
    SET is_active = false, updated_by = p_admin_user_id
    WHERE employee_id = p_employee_id;
END;
$$;

CREATE OR REPLACE PROCEDURE sp_add_stock(
    p_department_id INT,
    p_product_id INT,
    p_added_quantity INT,
    p_user_id INT
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_added_quantity IS NULL OR p_added_quantity <= 0 THEN
        RAISE EXCEPTION 'The quantity to be taken into inventory must be greater than zero (transferred: %)', p_added_quantity;
    END IF;

    IF p_user_id IS NULL OR NOT EXISTS (SELECT 1 FROM user_account WHERE id = p_user_id AND is_active = true) THEN
        RAISE EXCEPTION 'Valid and active User ID is required for stock audit';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM department WHERE id = p_department_id AND is_deleted = false) THEN
        RAISE EXCEPTION 'Department % does not exist or is inactive', p_department_id;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM product WHERE id = p_product_id AND is_deleted = false) THEN
        RAISE EXCEPTION 'Product % does not exist or is inactive', p_product_id;
    END IF;

    INSERT INTO department_stock (department_id, product_id, quantity, updated_by)
    VALUES (p_department_id, p_product_id, p_added_quantity, p_user_id)
    ON CONFLICT (department_id, product_id)
    DO UPDATE SET 
        quantity = department_stock.quantity + EXCLUDED.quantity,
        updated_by = EXCLUDED.updated_by;
END;
$$;

CREATE OR REPLACE PROCEDURE sp_cancel_receipt(
    p_transaction_id INT,
    p_admin_user_id INT
)
LANGUAGE plpgsql
AS $$
DECLARE
    item RECORD;
    v_dept_id INT;
    v_current_status VARCHAR(50);
BEGIN
    IF p_transaction_id IS NULL THEN RAISE EXCEPTION 'Transaction ID cannot be NULL';
    END IF;

    IF p_admin_user_id IS NULL OR NOT EXISTS (SELECT 1 FROM user_account WHERE id = p_admin_user_id AND is_active = true) THEN
        RAISE EXCEPTION 'Valid and active Admin User ID is required for cancellation audit';
    END IF;

    SELECT department_id, status 
    INTO v_dept_id, v_current_status
    FROM sales_transaction 
    WHERE id = p_transaction_id
    FOR UPDATE;

    IF NOT FOUND THEN RAISE EXCEPTION 'Transaction with ID % not found', p_transaction_id;
    END IF;

    IF v_current_status <> 'Completed' THEN
        RAISE EXCEPTION 'Cannot cancel receipt: status is "%", expected "Completed"', v_current_status;
    END IF;

    UPDATE sales_transaction 
    SET status = 'Cancelled', updated_by = p_admin_user_id
    WHERE id = p_transaction_id;

    FOR item IN (
        SELECT product_id, quantity 
        FROM sales_item 
        WHERE transaction_id = p_transaction_id
    ) 
    LOOP
        INSERT INTO department_stock (department_id, product_id, quantity, updated_by)
        VALUES (v_dept_id, item.product_id, item.quantity, p_admin_user_id)
        ON CONFLICT (department_id, product_id)
        DO UPDATE SET 
            quantity = department_stock.quantity + EXCLUDED.quantity,
            updated_by = EXCLUDED.updated_by;
    END LOOP;
END;
$$;

CREATE OR REPLACE PROCEDURE sp_create_sale(
    p_department_id INT,
    p_employee_id INT,
    p_product_id INT,
    p_quantity INT,
    p_customer_id INT DEFAULT NULL,
    p_user_id INT DEFAULT NULL
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_available_qty INT;
    v_unit_price NUMERIC(12, 2);
    v_total_amount NUMERIC(12, 2);
    v_transaction_id INT;
    v_product_name VARCHAR(200);
    v_dept_name VARCHAR(100);
BEGIN
    IF p_quantity IS NULL OR p_quantity <= 0 THEN RAISE EXCEPTION 'Quantity must be greater than zero';
    END IF;

    IF p_user_id IS NULL OR NOT EXISTS (
        SELECT 1 FROM user_account WHERE id = p_user_id AND is_active = true
    ) THEN RAISE EXCEPTION 'Valid and active User ID is required for sale audit';
    END IF;

    SELECT name INTO v_dept_name
    FROM department 
    WHERE id = p_department_id AND is_deleted = false;

    IF v_dept_name IS NULL THEN RAISE EXCEPTION 'Department #% does not exist or is inactive', p_department_id;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM employee 
        WHERE id = p_employee_id AND is_deleted = false
    ) THEN RAISE EXCEPTION 'Employee #% does not exist or is inactive', p_employee_id;
    END IF;

    IF p_customer_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM customer WHERE id = p_customer_id AND is_deleted = false
    ) THEN RAISE EXCEPTION 'Customer #% does not exist or is inactive', p_customer_id;
    END IF;

    SELECT name, price INTO v_product_name, v_unit_price
    FROM product 
    WHERE id = p_product_id AND is_deleted = false;

    IF v_product_name IS NULL THEN RAISE EXCEPTION 'Product #% is not active or does not exist', p_product_id;
    END IF;

    SELECT quantity INTO v_available_qty
    FROM department_stock
    WHERE department_id = p_department_id AND product_id = p_product_id
    FOR UPDATE;

    IF v_available_qty IS NULL THEN RAISE EXCEPTION 'Product "%" is not stocked in department "%"', v_product_name, v_dept_name;
    END IF;

    IF v_available_qty < p_quantity THEN 
        RAISE EXCEPTION 'Insufficient stock for "%" in "%": requested %, available %', v_product_name, v_dept_name, p_quantity, v_available_qty;
    END IF;

    v_total_amount := v_unit_price * p_quantity;

    INSERT INTO sales_transaction (department_id, employee_id, customer_id, transaction_date, total_amount, status, updated_by)
    VALUES (p_department_id, p_employee_id, p_customer_id, LOCALTIMESTAMP, v_total_amount, 'Completed', p_user_id)
    RETURNING id INTO v_transaction_id;

    INSERT INTO sales_item (transaction_id, product_id, quantity, unit_price)
    VALUES (v_transaction_id, p_product_id, p_quantity, v_unit_price);

    UPDATE department_stock
    SET quantity = quantity - p_quantity, updated_by = p_user_id
    WHERE department_id = p_department_id AND product_id = p_product_id;
END;
$$;

