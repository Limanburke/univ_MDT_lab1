CREATE OR REPLACE FUNCTION trg_check_category_soft_delete()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.is_deleted = true AND (OLD.is_deleted = false OR OLD.is_deleted IS NULL) THEN
        IF EXISTS (
            SELECT 1
            FROM category
            WHERE parent_category_id = NEW.id AND is_deleted = false
        ) THEN RAISE EXCEPTION 'Cannot soft-delete category with ID %: active subcategories exist', NEW.id;
        END IF;

        IF EXISTS (
            SELECT 1 
            FROM product 
            WHERE category_id = NEW.id AND is_deleted = false
        ) THEN RAISE EXCEPTION 'Cannot soft-delete category with ID %: active products exist in this category', NEW.id;
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER trg_category_prevent_delete_with_children
BEFORE UPDATE OF is_deleted ON category
FOR EACH ROW
EXECUTE FUNCTION trg_check_category_soft_delete();

CREATE OR REPLACE VIEW v_active_products AS
SELECT 
    p.id AS product_id,
    p.sku,
    p.name AS product_name,
    p.price,
    c.name AS category_name,
    s.name AS supplier_name,
    p.updated_at,
    COALESCE(e.first_name || ' ' || e.last_name, ua.username, 'System') AS updated_by_name
