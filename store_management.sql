    customer_id      integer REFERENCES customer(id),
    transaction_date timestamp without time zone NOT NULL,
    total_amount     numeric(12, 2) NOT NULL,
    status           varchar(50) NOT NULL DEFAULT 'Completed',
    updated_at       timestamp without time zone NOT NULL DEFAULT LOCALTIMESTAMP,
    updated_by       integer REFERENCES user_account(id),
    CONSTRAINT ck_sales_transaction_total_nonnegative CHECK (total_amount >= 0),
    CONSTRAINT ck_sales_transaction_status CHECK (status IN ('Completed', 'Cancelled', 'Returned'))
